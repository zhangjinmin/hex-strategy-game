/**
 * intelFreshness.ts — 情报**新鲜度分档**（唯一真源）
 *
 * ============================================================================
 * 与 IntelSystem 的关系（边界，读完再改）
 * ============================================================================
 * · `IntelSystem`（`game/battle/IntelSystem.js`）的档案**永不删除、无 TTL**
 *   —— 见 `IntelSystem.d.ts:31` 的「持久已知目标档案（团队域 · 无 TTL）」。
 * · 本模块**只描述「消费者如何解读档案年龄」**（权重 / 运动目标资格 / 显示档位），
 *   **不改变档案存储语义**。
 * ⚠ **禁止在本模块内做任何写档案的操作**（无 record / 无 prune / 无缓存）。
 *
 * ============================================================================
 * 为什么要独立成一个模块
 * ============================================================================
 * 后续多处都要问「这条情报还新不新」：B3 的战力权重、C0 的「能否当运动目标」、
 * S4 的显示档位。**如果每处各写一遍 10s / 25s，迟早会漂移** ——
 * 本轮已经出现过 7 套互相矛盾的视野数值，成因完全相同。
 * ⇒ 把阈值放在一个所有人都够得着的地方，是"防漂移"唯一有效的工程手段
 *   （而不是靠提醒"别写重复值"）。
 *
 * ⚠ **零依赖**：本文件不得 import 任何东西。
 *   台架用 CJS `require('.../intelFreshness.ts')` 直接加载，
 *   任何传递依赖都会 `ERR_MODULE_NOT_FOUND`。
 *
 * ============================================================================
 * 分档口径（闭区间）
 * ============================================================================
 *   age ≤ 10_000ms            → fresh（权重 1.0）
 *   age ≤ 25_000ms            → stale（权重 0.7）
 *   age > 25_000ms / 非有限值 → cold （权重 0，**不计入**加权均值）
 *
 * 两个反直觉边界的理由（不要"顺手改掉"）：
 * · **`-1` → fresh**（负年龄只可能来自时钟回拨或写入了未来时间戳）：
 *   判 cold 会让一次时钟异常**静默清空全队情报** —— 小故障放大成"战略失明"；
 *   判 fresh 只是让这条记录**继续参与**战力估算，而它的 `x/y` 至少是真实写过的位置。
 *   两者相权取 fresh。
 * · **`NaN` → cold**：必须**显式** `Number.isFinite` 判断，
 *   不能依赖 `NaN <= x === false` 这种隐式巧合 —— 有人重排比较顺序就会破。
 */

/** 「新鲜」上限（含）。超过即 stale。 */
export const INTEL_FRESH_MS = 10_000;

/** 「可用」上限（含）。超过即 cold（不计权重）。 */
export const INTEL_STALE_MS = 25_000;

export type IntelAgeTier = 'fresh' | 'stale' | 'cold';

/**
 * 档案年龄 → 新鲜度档位。
 *
 * ⚠ 闭区间：`10_000` 仍是 fresh、`25_000` 仍是 stale（边界归前一档）。
 * ⚠ 非有限值（`NaN` / `±Infinity` / 运行期的 `undefined`）一律 cold：
 *   "不知道"就按"过期"处理 —— 与 `-1` 的取向相反，因为两者语义不同
 *   （`-1` 是"刚写过但时钟回拨"，非有限值是"根本没有可信的时间"）。
 */
export function intelAgeTier(ageMs: number): IntelAgeTier {
  if (!Number.isFinite(ageMs)) return 'cold';
  if (ageMs <= INTEL_FRESH_MS) return 'fresh';
  if (ageMs <= INTEL_STALE_MS) return 'stale';
  return 'cold';
}

/**
 * 档位 → 战力权重。
 * ⚠ `cold` 返回 0：调用方必须用**加权均值** `Σ(power×w)/Σw`，
 *   不能把 `w = 0` 的样本计入分母（否则"看到 3 支但全过期"会把均值稀释掉）。
 */
export function intelTierWeight(tier: IntelAgeTier): number {
  return tier === 'fresh' ? 1 : tier === 'stale' ? 0.7 : 0;
}

/**
 * C0 的「能否作为运动目标」年龄上限。
 * ⚠ 必须与 `INTEL_STALE_MS` **同源**（同一性断言：两个名字是同一个值），
 *   不允许另写一个 25_000。
 */
export const CONTACT_TARGET_MAX_AGE_MS = INTEL_STALE_MS;
